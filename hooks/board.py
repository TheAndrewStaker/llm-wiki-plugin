#!/usr/bin/env python3
"""Generate the priority-ranked board from initiative frontmatter -- the single source
(KNOWLEDGE.md's 2026-07-14 "Assignments" rule). Priority is a dense rank the user states
explicitly (never inferred); unset priority falls back to a config-driven default by kind
and cycle. See docs/state-board.md in the wiki (or the wiki's own analyses/ page) for the
rule this implements; nothing about the rule itself is hardcoded here, only the mechanics.

Usage:
  board.py [WIKI_ROOT]                  print the board to stdout
  board.py [WIKI_ROOT] --write          replace the block between <!-- board:begin -->
                                         and <!-- board:end --> in STATE.md
  board.py [WIKI_ROOT] --repo NAME      also print a resume block: every initiative whose
                                         repos lists NAME (next, verify, waiting, open
                                         scopes, page), or, when none does, one "Where NAME
                                         stands" line for the first Now/Next row not waiting
                                         on anyone that carries no repos
"""
import argparse
import datetime
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wikilib

BEGIN = "<!-- board:begin (generated by hooks/board.py from initiative frontmatter; do not edit) -->"
END = "<!-- board:end -->"
KIND_ORDER = {"pitch": 0, "assigned": 1, "self": 2}
MAX_ROWS = 12
STALE_RANK_DAYS = 30
MAX_RESUME = 3
MAX_SCOPES = 6
SCOPE_RE = re.compile(r"(?m)^### (.+?) · (planned|active|review|done)\s*$")


def scope_lines(text):
    return [(n.strip(), s) for n, s in SCOPE_RE.findall(text)]


def unquote(v):
    v = (v or "").strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    return v


def wc(s):
    return len(s.split()) if s else 0


def load_initiatives(kb):
    out = []
    for f in wikilib.git_files(kb):
        if not f.startswith("initiatives/") or os.path.basename(f) == "index.md":
            continue
        text = wikilib.read(kb, f)
        fmblock = re.match(r"^---\n(.*?)\n---", text, re.S)
        if not fmblock:
            continue
        fm = fmblock.group(1)
        if wikilib.frontmatter_value(fm, "type") != "initiative":
            continue
        if wikilib.frontmatter_value(fm, "board") == "false":
            continue
        out.append({
            "path": f,
            "slug": os.path.splitext(os.path.basename(f))[0],
            "title": wikilib.frontmatter_value(fm, "title") or f,
            "kind": wikilib.frontmatter_value(fm, "assignment_kind") or "",
            "status": wikilib.frontmatter_value(fm, "assignment_status") or "",
            "priority": wikilib.frontmatter_value(fm, "priority"),
            "priority_set": wikilib.frontmatter_value(fm, "priority_set"),
            "cycle": wikilib.frontmatter_value(fm, "cycle"),
            "next": wikilib.frontmatter_value(fm, "next") or "",
            "verify": wikilib.frontmatter_value(fm, "verify") or "",
            "waiting_on": wikilib.frontmatter_value(fm, "waiting_on") or "none",
            "ask": wikilib.frontmatter_value(fm, "ask") or "",
            "repos": wikilib.fm_list(fm, "repos"),
            "timestamp": wikilib.frontmatter_value(fm, "timestamp") or "",
            "scopes": scope_lines(text),
        })
    return out


def default_rank(item, current_cycle):
    if item["status"] == "parked":
        return 9
    if item["kind"] == "pitch":
        if current_cycle and item["cycle"] == str(current_cycle):
            return 1
        return 2
    if item["kind"] == "assigned":
        return 2
    return 3


def tier_of(item, schema):
    """Tier from `kind_tier` ({kind: int}, lower outranks); absent config puts every item in
    tier 0, so priority alone orders the board."""
    tiers = schema.get("kind_tier") or {}
    return int(tiers.get(item["kind"], max(tiers.values(), default=0)))


def rank_of(item, current_cycle):
    p = item["priority"]
    if p and p.lstrip("-").isdigit():
        return int(p)
    return default_rank(item, current_cycle)


def stale_rank(item, today):
    ps = item["priority_set"]
    if not ps:
        return False
    try:
        age = (today - datetime.date.fromisoformat(ps)).days
    except ValueError:
        return False
    return age > STALE_RANK_DAYS


def sort_key(item):
    return (
        item.get("tier", 0),
        item["rank"],
        item["waiting_on"] != "none",
        KIND_ORDER.get(item["kind"], 3),
        item["timestamp"],
    )


def fmt_row(item, today):
    tag = "·".join(x for x in (item["kind"], item["status"],
                                f"c{item['cycle']}" if item["cycle"] else "") if x)
    line = f"{item['rank']}. [{tag}] {item['title']} → next: {item['next']}"
    if item.get("verify"):
        line += f" → verify: {item['verify']}"
    if item["repos"]:
        line += f" (repos: {', '.join(item['repos'])})"
    if item["waiting_on"] != "none":
        line += f" [waiting on {item['waiting_on']}: {item['ask']}]"
    if stale_rank(item, today):
        line += f" → stale, set {item['priority_set']}"
    return line


def _iso(v):
    try:
        return datetime.date.fromisoformat((v or "").strip().strip("\"'"))
    except ValueError:
        return None


def resolve_period(kb, cfg, today):
    """Derive the current period (label, end date, provenance) from per-period markdown files.

    Optional config `cycle_source` (an object):
      glob         required; one markdown file per period. `~` and a path relative to the
                   wiki root are both expanded.
      start_field  frontmatter key holding the start date (default "start")
      end_field    key holding the end date the board SHOWS (default "end")
      window_end_field  key that closes the period's window for "is it current?" (default:
                   end_field). Lets a period stay current through a trailing phase.
      label_field  frontmatter key holding the label; when absent the label is the first
                   capture group of label_regex run on the file name (default "(\\d+)").

    The current period is the file whose start <= today <= window end (latest start wins on
    overlap); with none, the most recent past one, flagged. Returns None when cycle_source is
    not configured, else a dict; an unreadable or empty source is reported in `note` and never
    raises, so a commit hook is never broken by an unsynced directory.
    """
    spec = cfg.get("cycle_source")
    if not isinstance(spec, dict) or not spec.get("glob"):
        return None
    start_f = spec.get("start_field", "start")
    end_f = spec.get("end_field", "end")
    win_f = spec.get("window_end_field", end_f)
    label_f = spec.get("label_field")
    label_re = spec.get("label_regex", r"(\d+)")
    pattern = os.path.expanduser(spec["glob"])
    if not os.path.isabs(pattern):
        pattern = os.path.join(kb, pattern)
    try:
        files = sorted(glob.glob(pattern))
    except Exception as exc:  # defensive: a bad pattern must not break a hook
        return {"note": f"cycle_source unusable ({exc})"}
    periods = []
    for f in files:
        try:
            with open(f, encoding="utf-8") as fh:
                text = fh.read(8192)
        except OSError:
            continue
        block = re.match(r"^---\n(.*?)\n---", text, re.S)
        if not block:
            continue
        fm = block.group(1)
        start = _iso(wikilib.frontmatter_value(fm, start_f))
        end = _iso(wikilib.frontmatter_value(fm, end_f))
        win = _iso(wikilib.frontmatter_value(fm, win_f)) or end
        if not (start and end and win):
            continue
        label = wikilib.frontmatter_value(fm, label_f) if label_f else None
        if not label:
            m = re.search(label_re, os.path.basename(f))
            label = m.group(1) if m and m.groups() else None
        if not label:
            continue
        periods.append({"label": label, "start": start, "end": end, "win": win,
                        "file": os.path.basename(f)})
    if not periods:
        return {"note": "cycle_source matched no readable period files "
                        "(source not synced?); using config values"}
    current = [p for p in periods if p["start"] <= today <= p["win"]]
    if current:
        best = max(current, key=lambda p: p["start"])
        best["flag"] = ""
    else:
        past = [p for p in periods if p["win"] < today]
        if not past:
            return {"note": "cycle_source has no period covering today; using config values"}
        best = max(past, key=lambda p: p["win"])
        best["flag"] = "most recent past, none covers today"
    return best


def build(kb, repo=None):
    cfg = wikilib.load_config(kb)
    current_cycle = cfg.get("current_cycle")
    cycle_ends = cfg.get("cycle_ends")
    today = datetime.date.today()
    cycle_note = ""
    try:
        per = resolve_period(kb, cfg, today)
    except Exception as exc:  # never let period derivation break a commit hook
        per = {"note": f"cycle_source failed ({exc}); using config values"}
    if per and per.get("label"):
        current_cycle, cycle_ends = per["label"], per["end"].isoformat()
        cycle_note = f" [from {per['file']}" + (f"; {per['flag']}" if per["flag"] else "") + "]"
    elif per:
        cycle_note = f" [{per['note']}]"
    elif current_cycle or cycle_ends:
        cycle_note = " [hand-set in config]"

    schema = cfg.get("initiative_schema") or {}
    items = load_initiatives(kb)
    shipped, active = [], []
    for it in items:
        if it["status"] == "done":
            shipped.append(it)
            continue
        it["rank"] = rank_of(it, current_cycle)
        it["tier"] = tier_of(it, schema)
        active.append(it)
    active.sort(key=sort_key)

    later_rows = [i for i in active if i["rank"] >= 6]
    shown_rows = [i for i in active if i["rank"] <= 5]
    tier_labels = schema.get("tier_labels") or []
    if schema.get("kind_tier"):
        sections = []
        for t in sorted({i["tier"] for i in shown_rows} | set(range(len(tier_labels)))):
            label = tier_labels[t] if t < len(tier_labels) else f"Tier {t + 1}"
            sections.append((label, [i for i in shown_rows if i["tier"] == t]))
    else:
        sections = [("Now", [i for i in shown_rows if i["rank"] <= 2]),
                    ("Next", [i for i in shown_rows if i["rank"] >= 3])]

    lines = [BEGIN]
    ts = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    hdr = f"## Board (generated {ts}"
    if current_cycle:
        hdr += f" · cycle {current_cycle}"
        if cycle_ends:
            try:
                ended = datetime.date.fromisoformat(cycle_ends) < today
            except ValueError:
                ended = False
            hdr += f" ends {cycle_ends}" + (
                " -- PASSED" + ("" if per and per.get("label") else ", re-set cycle_ends")
                if ended else "")
    hdr += cycle_note
    cap = (cfg.get("initiative_schema") or {}).get("active_max") or 0
    if cap:
        n_active = sum(1 for i in active if i["status"] == "active")
        hdr += f" · active {n_active}/{cap}"
    hdr += " · priority is a rank you state, 1-9"
    if schema.get("kind_tier"):
        hdr += ", within a tier"
    hdr += ")"
    lines.append(hdr)

    owner, owner_label = wikilib.queue_owner(cfg.get("initiative_schema"))
    waiting_owner = [i for i in active if i["waiting_on"] == owner]
    oa_text = wikilib.read(kb, f"open-asks/{owner}.md")
    oa_items = re.findall(r"(?m)^- (.+)$", oa_text)
    queue_total = len(waiting_owner) + len(oa_items)
    oldest = ""
    if schema.get("queue_dated"):
        dates = [_iso(q["date"]) for q in wikilib.parse_queue(oa_text) if q["date"]]
        dates = [d for d in dates if d]
        if dates:
            oldest = f", oldest {(today - min(dates)).days}d"
    lines.append(f"Waiting on {owner_label} ({queue_total}{oldest}):")
    for i in waiting_owner:
        lines.append(f"- {i['slug']} · {i['ask']}")
    for line in oa_items:
        lines.append(f"- (open-asks/{owner}) {line}")

    shown = 0
    for label, rows in sections:
        lines.append(f"{label}:")
        for i in rows:
            if shown >= MAX_ROWS:
                break
            lines.append(fmt_row(i, today))
            shown += 1
    remaining = len(shown_rows) - shown
    if remaining > 0:
        lines.append(f"+{remaining} more")

    lines.append("Later / parked: " + (" · ".join(i["slug"] for i in later_rows) or "none"))
    recent_shipped = sorted(
        (i for i in shipped if i["timestamp"]),
        key=lambda i: i["timestamp"], reverse=True,
    )[:5]
    lines.append("Shipped: " + (" · ".join(i["slug"] for i in recent_shipped) or "none"))
    lines.append(END)
    board = "\n".join(lines)

    pointer = None
    if repo:
        bound = [i for i in active if repo in i["repos"]]
        if bound:
            out = []
            for i in bound[:MAX_RESUME]:
                line = f"Resume {i['slug']} (#{i['rank']}, {i['status']}): next → {unquote(i['next'])}"
                if i["verify"]:
                    line += f" → verify: {unquote(i['verify'])}"
                if i["waiting_on"] != "none":
                    line += f" [waiting on {i['waiting_on']}: {unquote(i['ask'])}]"
                open_scopes = [f"{n} · {st}" for n, st in i["scopes"] if st != "done"]
                if open_scopes:
                    line += " → scopes: " + "; ".join(open_scopes[:MAX_SCOPES])
                    if len(open_scopes) > MAX_SCOPES:
                        line += f"; +{len(open_scopes) - MAX_SCOPES} more"
                line += f" → page: {i['path']}"
                out.append(line)
            if len(bound) > MAX_RESUME:
                out.append(f"+{len(bound) - MAX_RESUME} more initiatives list {repo}")
            pointer = "\n".join(out)
        else:
            for i in shown_rows:
                if i["waiting_on"] != "none" or i["repos"]:
                    continue
                pointer = (f"Where {repo} stands: #{i['rank']} {i['title']} → {i['next']}"
                           f" (no initiative lists {repo} in repos:)")
                break
    return board, pointer


def write_state(kb, board):
    path = os.path.join(kb, "STATE.md")
    text = wikilib.read(kb, "STATE.md")
    if not text:
        return False
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        print(f"board.py: no {BEGIN} .. {END} markers in STATE.md; nothing written", file=sys.stderr)
        return False
    new_text = pattern.sub(lambda _: board.replace("\\", "\\\\"), text, count=1)
    stamp = re.compile(r"\(generated \d{4}-\d\d-\d\d \d\d:\d\d")
    if stamp.sub("", new_text) == stamp.sub("", text):
        return False
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(new_text)
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root", nargs="?", default=None)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--repo", default=None)
    args = ap.parse_args()
    kb = wikilib.resolve_root(args.root)
    board, pointer = build(kb, repo=args.repo)
    if args.write:
        write_state(kb, board)
    else:
        print(board)
    if pointer:
        print(pointer)


if __name__ == "__main__":
    main()
