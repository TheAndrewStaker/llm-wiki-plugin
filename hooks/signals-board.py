#!/usr/bin/env python3
"""Generate the signals index from signal-page frontmatter, and surface due dates.

A signal is an external development with a lifecycle (a rule, a lawsuit, a recurring
report, a market story), one page per storyline under the configured directory. Its
frontmatter is the single source; the index table is generated, never hand-edited.

Config (wiki.config.json), feature off when absent:
  "signals": {
    "dir": "signals/",
    "warn_days": 14,
    "relevance": ["direct", "adjacent", "background"],
    "kinds": {"rule": ["proposed", "final", "effective", "withdrawn"], ...},
    "closed": ["effective", "withdrawn"]
  }

Page frontmatter: type: signal, kind, stage, relevance, next_expected (YYYY-MM-DD),
next_expected_what, recheck (YYYY-MM-DD), last_event (YYYY-MM-DD), aliases.

Usage:
  signals-board.py [WIKI_ROOT]            print the index block
  signals-board.py [WIKI_ROOT] --write    replace the marked block in <dir>/index.md
  signals-board.py [WIKI_ROOT] --due      session-start lines for dates within warn_days
  signals-board.py [WIKI_ROOT] --check    field and vocabulary issues, one per line
  signals-board.py [WIKI_ROOT] --find ID  signals whose slug, title or an alias equals ID
                                          (case- and punctuation-insensitive); exit 1 if none
  --index                                 read pages from the git index, not the working tree
                                          (pre-commit: the table matches what is committed)
"""
import argparse
import datetime
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wikilib

BEGIN = "<!-- signals:begin (generated by hooks/signals-board.py from signal frontmatter; do not edit) -->"
END = "<!-- signals:end -->"
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def config(kb):
    sig = wikilib.load_config(kb).get("signals")
    if not isinstance(sig, dict) or not sig.get("dir"):
        return None
    sig = dict(sig)
    sig["dir"] = sig["dir"].rstrip("/") + "/"
    return sig


def date_or_none(value):
    if value and DATE_RE.match(value):
        try:
            return datetime.date.fromisoformat(value)
        except ValueError:
            return None
    return None


def page_texts(kb, cfg, from_index=False):
    if from_index:
        out = subprocess.run(["git", "ls-files", "-z", "--", cfg["dir"]], cwd=kb,
                             capture_output=True, text=True).stdout
        for rel in sorted(f for f in out.split("\0") if f):
            if "/" in rel[len(cfg["dir"]):] or not rel.endswith(".md"):
                continue
            r = subprocess.run(["git", "show", f":{rel}"], cwd=kb, capture_output=True, text=True)
            if r.returncode == 0:
                yield os.path.basename(rel), r.stdout
        return
    root = os.path.join(kb, cfg["dir"])
    if not os.path.isdir(root):
        return
    for f in sorted(os.listdir(root)):
        if not f.endswith(".md"):
            continue
        try:
            yield f, open(os.path.join(root, f), encoding="utf-8").read()
        except OSError:
            continue


def load_pages(kb, cfg, from_index=False):
    pages = []
    for f, text in page_texts(kb, cfg, from_index):
        if f == "index.md" or not wikilib.fm_block(text):
            continue
        get = lambda k: (wikilib.frontmatter_value(text, k) or "").strip().strip("'\"")
        if get("type") != "signal":
            continue
        pages.append({
            "file": f,
            "title": get("title") or f[:-3],
            "kind": get("kind"),
            "stage": get("stage"),
            "relevance": get("relevance"),
            "next_expected": get("next_expected"),
            "next_what": get("next_expected_what"),
            "recheck": get("recheck"),
            "last_event": get("last_event"),
            "aliases": wikilib.frontmatter_values(text, "aliases"),
        })
    return pages


def issues(pages, cfg):
    kinds = cfg.get("kinds") or {}
    relevance = cfg.get("relevance") or []
    out = []
    for p in pages:
        f = p["file"]
        for key in ("kind", "stage", "relevance"):
            if not p[key]:
                out.append(f"{f}: missing {key}")
        if kinds and p["kind"] and p["kind"] not in kinds:
            out.append(f"{f}: kind '{p['kind']}' not in {sorted(kinds)}")
        allowed = kinds.get(p["kind"]) if kinds else None
        if allowed and p["stage"] and p["stage"] not in allowed:
            out.append(f"{f}: stage '{p['stage']}' not allowed for kind '{p['kind']}' {allowed}")
        if relevance and p["relevance"] and p["relevance"] not in relevance:
            out.append(f"{f}: relevance '{p['relevance']}' not in {relevance}")
        for key in ("next_expected", "recheck", "last_event"):
            if p[key] and not date_or_none(p[key]):
                out.append(f"{f}: {key} '{p[key]}' is not YYYY-MM-DD")
        closed = p["stage"] in (cfg.get("closed") or [])
        if not closed and not date_or_none(p["next_expected"]) and not date_or_none(p["recheck"]):
            out.append(f"{f}: open signal has neither next_expected nor recheck, so nothing resurfaces it")
    return out


def cell(text):
    return (text or "").replace("|", "/")


def render(pages, cfg):
    closed_set = set(cfg.get("closed") or [])
    open_rows = [p for p in pages if p["stage"] not in closed_set]
    closed_rows = [p for p in pages if p["stage"] in closed_set]
    far = datetime.date.max

    def due(p):
        dates = [d for d in (date_or_none(p["next_expected"]), date_or_none(p["recheck"])) if d]
        return min(dates) if dates else far

    open_rows.sort(key=lambda p: (due(p), p["title"].lower()))
    closed_rows.sort(key=lambda p: (p["last_event"] or ""), reverse=True)
    lines = [BEGIN, "", f"## Open ({len(open_rows)})", "",
             "| Signal | Kind | Stage | Relevance | Next expected | Recheck | Last event |",
             "|---|---|---|---|---|---|---|"]
    for p in open_rows:
        nxt = " ".join(x for x in (p["next_expected"], p["next_what"]) if x)
        lines.append(f"| [{cell(p['title'])}]({p['file']}) | {p['kind']} | {p['stage']} | "
                     f"{p['relevance']} | {cell(nxt)} | {p['recheck']} | {p['last_event']} |")
    lines += ["", f"## Closed ({len(closed_rows)})", ""]
    if closed_rows:
        lines += ["| Signal | Kind | Stage | Last event |", "|---|---|---|---|"]
        for p in closed_rows:
            lines.append(f"| [{cell(p['title'])}]({p['file']}) | {p['kind']} | {p['stage']} | {p['last_event']} |")
    else:
        lines.append("(none)")
    lines += ["", END]
    return "\n".join(lines)


def write(kb, cfg, block):
    path = os.path.join(kb, cfg["dir"], "index.md")
    try:
        text = open(path, encoding="utf-8").read()
    except OSError:
        return False
    if BEGIN not in text or END not in text:
        return False
    new = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    if new != text:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(new)
    return True


def due_lines(pages, cfg, today=None):
    today = today or datetime.date.today()
    warn = int(cfg.get("warn_days", 14))
    closed_set = set(cfg.get("closed") or [])
    rows = []
    for p in pages:
        if p["stage"] in closed_set:
            continue
        for key, label in (("next_expected", p["next_what"] or "next expected event"),
                           ("recheck", "recheck status")):
            d = date_or_none(p[key])
            if d is None:
                continue
            days = (d - today).days
            if days <= warn:
                rows.append((days, p["file"][:-3], p[key], label))
    out = []
    for days, slug, date, what in sorted(rows):
        when = (f"PAST {-days}d ({date})" if days < 0 else
                f"TODAY ({date})" if days == 0 else f"in {days}d ({date})")
        out.append(f"Signal [{slug}] {when}: {what}")
    return out


def norm(text):
    return re.sub(r"[^a-z0-9]", "", (text or "").lower())


def find(pages, term):
    key = norm(term)
    if not key:
        return []
    return [p for p in pages
            if any(key == norm(name) for name in [p["file"][:-3], p["title"], *p["aliases"]])]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root", nargs="?")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--due", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--find", metavar="ID")
    ap.add_argument("--today")
    ap.add_argument("--index", action="store_true")
    args = ap.parse_args()
    kb = wikilib.resolve_root(args.root)
    cfg = config(kb)
    if cfg is None:
        return 0
    pages = load_pages(kb, cfg, from_index=args.index)
    if args.due:
        today = datetime.date.fromisoformat(args.today) if args.today else None
        for line in due_lines(pages, cfg, today):
            print(line)
        return 0
    if args.find is not None:
        hits = find(pages, args.find)
        for p in hits:
            print(f"{os.path.join(cfg['dir'], p['file'])}\t{p['stage']}\t{p['title']}")
        return 0 if hits else 1
    if args.check:
        found = issues(pages, cfg)
        for line in found:
            print(f"SIGNAL {line}")
        return 1 if found else 0
    block = render(pages, cfg)
    if args.write:
        write(kb, cfg, block)
    else:
        print(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
